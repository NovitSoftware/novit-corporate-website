/**
 * A route between two points: a shallow arc rather than a straight rule, so
 * it reads as a connection and not as a border. It bows north, or east when
 * it runs north itself, so the routes fan out of their shared origin instead
 * of crossing.
 */
export function route(from: { x: number; y: number }, to: { x: number; y: number }): string {
  const dx = to.x - from.x;
  const dy = to.y - from.y;
  const length = Math.hypot(dx, dy) || 1;
  const nx = -dy / length;
  const ny = dx / length;
  const side = Math.abs(ny) < 0.25 ? Math.sign(nx) || 1 : ny < 0 ? 1 : -1;
  const bow = Math.min(110, length * 0.2) * side;
  const cx = (from.x + to.x) / 2 + nx * bow;
  const cy = (from.y + to.y) / 2 + ny * bow;
  return `M${from.x.toFixed(1)} ${from.y.toFixed(1)} Q${cx.toFixed(1)} ${cy.toFixed(1)} ${to.x.toFixed(1)} ${to.y.toFixed(1)}`;
}

