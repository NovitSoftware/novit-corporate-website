/*
 * The customer map's geometry, in the coordinates of `/maps/world.svg`.
 *
 * The world is drawn as an image — every country's outline at one weight —
 * and Argentina again on top of it, from the same file's own `AR` path —
 * the mainland and las Islas Malvinas — so the two line up to the pixel and
 * the home country can carry its own ink.
 */

/* `/maps/world.svg` is Robinson; these place a lat/lon in its viewBox, fitted
   against the US, Brazil, Spain, Argentina and Colombia outlines. */
const ORIGIN_X = 977.8;
const ORIGIN_Y = 497.6;
const SCALE_X = 5.63;
const SCALE_Y = 514;

/** A lat/lon on the map. */
export function place(lat: number, lon: number): { x: number; y: number } {
  const [x, y] = robinson(lat, lon);
  return { x: ORIGIN_X + SCALE_X * x, y: ORIGIN_Y - SCALE_Y * y };
}

